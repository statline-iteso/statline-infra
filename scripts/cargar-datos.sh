#!/usr/bin/env bash
# Loads the data an environment needs after `make apply` and the Argo CD sync (D-46):
#   staging: demo data (D-42), then the backfill of the current seasons, then models.
#   prod:    the backfill of the current seasons only (live data, never demo), then models.
# The backfill runs `ingesta run <deporte> --desde <season start> --hasta <today+7>` as one-off Jobs
# from each CronJob spec. On the free plans every run goes through the fallbacks (balldontlie,
# TheSportsDB): real games and standings, no player box scores (D-40, D-41).
# Models are trained and forecasts generated by calling predicciones inside the namespace, from a
# curl pod with the smoke label (the NetworkPolicies already let it in), so no admin login is needed.
# Uses a throwaway kubeconfig, never the default context.
#
# Usage: scripts/cargar-datos.sh staging|prod
#   DESDE_BASQUETBOL, DESDE_AMERICANO, DESDE_FUTBOL  season starts (YYYY-MM-DD)
#   HASTA                                           last day to ingest (default: today + 7 days)
set -euo pipefail

env=${1:-}
case "$env" in staging|prod) ;; *) echo "usage: $0 staging|prod" >&2; exit 1;; esac
ns=statline-$env
rel=statline-$env
cluster=${CLUSTER_NAME:-statline}
region=${AWS_REGION:-us-east-1}

# Current seasons on 2026-11-25: NBA 2026-27 from Oct 20, NFL 2026 from Sep 9, Liga MX Apertura 2026
# from mid-July. Move them forward for the next season.
desde_basquetbol=${DESDE_BASQUETBOL:-2026-10-20}
desde_americano=${DESDE_AMERICANO:-2026-09-09}
desde_futbol=${DESDE_FUTBOL:-2026-07-16}
hasta=${HASTA:-$(date -u -v+7d +%F 2>/dev/null || date -u -d '+7 days' +%F)}
curl_image=curlimages/curl:8.11.1

kc=$(mktemp)
trap 'rm -f "$kc"' EXIT
aws eks update-kubeconfig --name "$cluster" --region "$region" --kubeconfig "$kc" >/dev/null
k() { kubectl --kubeconfig "$kc" "$@"; }

if ! k -n "$ns" get cronjob "$rel-ingesta-basquetbol" >/dev/null 2>&1; then
  echo "error: $ns has no ingesta CronJobs yet; wait for Argo CD to sync $rel" >&2
  exit 1
fi
k -n "$ns" rollout status "deploy/$rel-api" --timeout=5m >/dev/null
k -n "$ns" rollout status "deploy/$rel-predicciones" --timeout=5m >/dev/null

stamp=$(date +%s)

# One-off Job from a CronJob spec with other args; no retries (a rerun of the same range is safe:
# games are upserted by provider id, but a retry would only hit the same rate limits again).
lanzar() {
  local cron=$1 nombre=$2; shift 2
  local args
  args=$(printf '%s\n' "$@" | jq -R . | jq -s -c .)
  k -n "$ns" create job "$nombre" --from="cronjob/$rel-$cron" --dry-run=client -o json \
    | jq --argjson a "$args" '.spec.backoffLimit = 0 | .spec.template.spec.containers[0].args = $a' \
    | k apply -f - >/dev/null
  echo "$nombre: ${*}" >&2
}

# Waits for a Job to finish and prints its result line. Returns 1 if it failed.
esperar() {
  local nombre=$1 limite=$((SECONDS + 3600)) ok fallo
  while ((SECONDS < limite)); do
    ok=$(k -n "$ns" get job "$nombre" -o jsonpath='{.status.succeeded}')
    fallo=$(k -n "$ns" get job "$nombre" -o jsonpath='{.status.failed}')
    if [[ "$ok" == 1 || -n "$fallo" ]]; then break; fi
    sleep 10
  done
  k -n "$ns" logs "job/$nombre" 2>/dev/null | grep -E "Resultado(Ejecucion|Demo)|ERROR" | sed -E 's/^[0-9-]+ [0-9:,]+ //' >&2 || true
  [[ "$ok" == 1 ]] || { echo "error: job $nombre did not succeed" >&2; return 1; }
}

fallos=0

if [[ "$env" == staging ]]; then
  echo "== demo data (staging only, D-42)" >&2
  lanzar ingesta-basquetbol "datos-demo-$stamp" seed-demo --confirmar
  esperar "datos-demo-$stamp" || fallos=$((fallos + 1))
fi

echo "== backfill to $hasta (live data)" >&2
# NBA (balldontlie) runs alongside the TheSportsDB pair, which share one rate limit and go in turn.
lanzar ingesta-basquetbol "datos-nba-$stamp" run basquetbol --desde "$desde_basquetbol" --hasta "$hasta"
lanzar ingesta-americano "datos-nfl-$stamp" run americano --desde "$desde_americano" --hasta "$hasta"
esperar "datos-nfl-$stamp" || fallos=$((fallos + 1))
lanzar ingesta-futbol "datos-ligamx-$stamp" run futbol --desde "$desde_futbol" --hasta "$hasta"
esperar "datos-ligamx-$stamp" || fallos=$((fallos + 1))
esperar "datos-nba-$stamp" || fallos=$((fallos + 1))

echo "== models, forecasts and projections (predicciones, inside $ns)" >&2
# A model that cannot train (not enough games or box scores) or does not beat its baseline is
# reported in the response; it is not an error. Prod has no box scores, so no projection models.
pod="datos-modelos-$stamp"
# The container name must equal the pod name, or the strategic merge adds a second container.
overrides=$(jq -n -c --arg img "$curl_image" --arg pod "$pod" '{spec: {automountServiceAccountToken: false,
  securityContext: {runAsNonRoot: true, runAsUser: 100, runAsGroup: 101, seccompProfile: {type: "RuntimeDefault"}},
  containers: [{name: $pod, image: $img, stdin: true,
    securityContext: {allowPrivilegeEscalation: false, readOnlyRootFilesystem: true, capabilities: {drop: ["ALL"]}}}]}}')
k -n "$ns" run "$pod" --rm -i --restart=Never --image="$curl_image" \
  --labels=statline.io/smoke=true --override-type=strategic --overrides="$overrides" -- sh -s <<EOF >&2 || fallos=$((fallos + 1))
P=http://$rel-predicciones
for d in BASQUETBOL AMERICANO FUTBOL; do
  for t in RESULTADO_PARTIDO PROYECCION_JUGADOR; do
    printf '%s %s: ' "\$d" "\$t"
    curl -sS --max-time 900 -X POST "\$P/modelos/reentrenar" -H 'content-type: application/json' \
      -d "{\"deporte\":\"\$d\",\"tipo\":\"\$t\"}" | cut -c1-200
    echo
  done
done
for d in BASQUETBOL AMERICANO FUTBOL; do
  printf '%s pronosticos: ' "\$d"
  curl -sS --max-time 600 -X POST "\$P/pronosticos/generar" -H 'content-type: application/json' -d "{\"deporte\":\"\$d\"}" | cut -c1-200
  echo
  printf '%s proyecciones: ' "\$d"
  curl -sS --max-time 600 -X POST "\$P/proyecciones/generar" -H 'content-type: application/json' -d "{\"deporte\":\"\$d\"}" | cut -c1-200
  echo
done
EOF

echo "== summary ($ns)" >&2
# Counted from the api pod, which has the database credentials and the Prisma client.
# shellcheck disable=SC2016  # the single-quoted program is JavaScript; ${...} is JS, not shell
k -n "$ns" exec "deploy/$rel-api" -c api -- node -e '
const { PrismaClient } = require("@prisma/client");
const p = new PrismaClient();
(async () => {
  for (const deporte of ["BASQUETBOL", "AMERICANO", "FUTBOL"]) {
    const total = await p.partido.count({ where: { liga: { deporte } } });
    const demo = await p.partido.count({ where: { liga: { deporte }, proveedorId: { startsWith: "demo-" } } });
    const fin = await p.partido.count({ where: { liga: { deporte }, estatus: "FINALIZADO", NOT: { proveedorId: { startsWith: "demo-" } } } });
    const prog = await p.partido.count({ where: { liga: { deporte }, estatus: "PROGRAMADO" } });
    console.log(`${deporte.padEnd(10)} games: ${total - demo} live (${fin} finished, ${prog} scheduled), ${demo} demo`);
  }
  const activos = await p.modeloPrediccion.findMany({ where: { activo: true }, select: { deporte: true, tipo: true, version: true } });
  console.log("active models:", activos.length ? activos.map((m) => `${m.deporte}/${m.tipo} ${m.version}`).join(", ") : "none");
  const demo = await p.partido.count({ where: { proveedorId: { startsWith: "demo-" } } });
  if (process.argv[1] === "prod" && demo > 0) console.log(`WARNING: prod has ${demo} demo games (D-46 says live only)`);
  await p.$disconnect();
})();' "$env" >&2

if ((fallos > 0)); then
  echo "$fallos step(s) failed; see above" >&2
  exit 1
fi
echo "Data loaded in $ns." >&2
